# ==============================================
# PACOTE HANDLERS CLIENT
# ==============================================
# Este pacote contém os handlers das funcionalidades
# destinadas ao cliente final do bot.
#
# Módulos:
#   - start.py            -> /start e menu principal
#   - catalog.py          -> Navegação de categorias e produtos
#   - product.py          -> Detalhes do produto
#   - purchase.py         -> Fluxo de compra (saldo, quantidade, PIX)
#   - payment.py          -> Verificação de pagamento
#   - profile.py          -> Perfil do usuário
#   - history.py          -> Histórico de compras
#   - giftcard.py         -> Resgate de gift card
#   - recharge.py         -> Recarga de saldo via PIX
#   - affiliate.py        -> Programa de afiliados
#   - rankings.py         -> Rankings
#   - alerts.py           -> Alertas de reabastecimento
#   - search.py           -> Pesquisa inline
#   - special_commands.py -> /pix, /historico, /alerta, etc.
#   - inline.py           -> Handlers de inline query
#
# Este arquivo está vazio e serve apenas para marcar
# o diretório como um pacote Python.
